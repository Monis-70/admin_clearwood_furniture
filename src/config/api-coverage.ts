/**
 * API coverage: how every admin route of the ClearWood API is handled by this admin.
 *
 * One entry per mounted `/api/v1/admin` route, keyed `METHOD /suffix` (suffix after
 * /api/v1/admin). `npm run coverage:check` compares this table with the pinned route inventory
 * (contracts/route-inventory.json) and with the endpoint registry (src/lib/api/endpoints.ts), and
 * fails the build when a route is unclassified, an entry is stale, the UI calls a route that is on
 * hold or internal, or a route planned for an implemented phase is not wired yet.
 *
 * Build-time metadata only: never import this module from application code.
 *
 * kind: L list · G get · C create · U update (versioned) · u update (unversioned) · D delete ·
 *       A action · P preview/dry-run · R reorder · UP upload · DL download · AU auth/session
 * destructive: - none · R reversible (undo/restore exists) · X irreversible from the admin
 * status: P0..P10 build phase · hold:<domain> integration on hold · internal (never called by the UI)
 */

/** Routes planned for this phase or earlier must be present in the endpoint registry. */
export { IMPLEMENTED_THROUGH_PHASE } from './phase';

export type HoldDomain = 'payments' | 'refunds' | 'returns' | 'shipping' | 'email';
export type CoverageStatus = `P${number}` | `hold:${HoldDomain}` | 'internal';
export type RouteKind = 'L' | 'G' | 'C' | 'U' | 'u' | 'D' | 'A' | 'P' | 'R' | 'UP' | 'DL' | 'AU';
export type Destructive = '-' | 'R' | 'X';

export interface CoverageEntry {
  module: string;
  purpose: string;
  screen: string;
  action: string;
  kind: RouteKind;
  destructive: Destructive;
  status: CoverageStatus;
  notes?: string;
}

type Row = [
  key: string,
  purpose: string,
  screen: string,
  action: string,
  kind: RouteKind,
  destructive: Destructive,
  status: CoverageStatus,
  notes?: string,
];

