function section(module: string, rows: Row[]): Record<string, CoverageEntry> {
  const out: Record<string, CoverageEntry> = {};
  for (const [key, purpose, planScreen, action, kind, destructive, planStatus, notes] of rows) {
    const replan = REPLANNED[key];
    out[key] = {
      module,
      purpose,
      screen: replan?.screen ?? planScreen,
      action,
      kind,
      destructive,
      status: replan?.status ?? planStatus,
      ...(notes ? { notes } : {}),
    };
  }
  return out;
}

